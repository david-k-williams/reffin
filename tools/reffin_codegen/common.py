"""Shared deterministic code-generation helpers for Reffin domains."""

from __future__ import annotations

import csv
import hashlib
import json
import re
from pathlib import Path
from typing import Iterable, Mapping, Sequence


ROOT = Path(__file__).resolve().parents[2]
SNAKE_CASE = re.compile(r"[a-z][a-z0-9]*(?:_[a-z0-9]+)*")


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as stream:
        return list(csv.DictReader(stream))


def validate_rows(
    path: Path,
    rows: Sequence[Mapping[str, str]],
    *,
    id_field: str,
    required: Iterable[str],
    sorted_ids: bool = True,
) -> None:
    """Validate the common contract used by source-driven enum tables."""
    if not rows:
        raise ValueError(f"{path}: no data rows")
    required_fields = tuple(required)
    ids: list[str] = []
    for index, row in enumerate(rows, start=2):
        missing = [field for field in required_fields if not row.get(field)]
        if missing:
            raise ValueError(f"{path}:{index}: empty required fields: {', '.join(missing)}")
        value = row[id_field]
        if not SNAKE_CASE.fullmatch(value):
            raise ValueError(f"{path}:{index}: invalid snake_case ID {value!r}")
        ids.append(value)
    if len(ids) != len(set(ids)):
        raise ValueError(f"{path}: duplicate {id_field}")
    if sorted_ids and ids != sorted(ids):
        raise ValueError(f"{path}: rows must be sorted by {id_field}")


def fingerprint(paths: Iterable[Path], *, root: Path = ROOT) -> str:
    digest = hashlib.sha256()
    for path in sorted(paths):
        digest.update(path.relative_to(root).as_posix().encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def words(value: str) -> list[str]:
    return [part for part in re.split(r"[^A-Za-z0-9]+", value) if part]


def pascal(value: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in words(value))


def camel(value: str) -> str:
    result = pascal(value)
    return result[:1].lower() + result[1:]


DART_KEYWORDS = {
    "assert", "break", "case", "catch", "class", "const", "continue", "default",
    "do", "else", "enum", "extends", "false", "final", "finally", "for", "if",
    "in", "is", "new", "null", "rethrow", "return", "super", "switch", "this",
    "throw", "true", "try", "var", "void", "while", "with",
}


def dart_identifier(value: str) -> str:
    result = camel(value)
    return f"{result}Value" if result in DART_KEYWORDS else result


def py_string(value: str) -> str:
    return repr(value)


def ts_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def dart_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
    escaped = escaped.replace("\r", "\\r").replace("\n", "\\n")
    return f"'{escaped}'"


def write_or_check(path: Path, content: str, check: bool) -> bool:
    normalized = content.rstrip() + "\n"
    if check:
        return path.exists() and path.read_text(encoding="utf-8") == normalized
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(normalized, encoding="utf-8")
    return True


def generated_banner(language: str, domain: str, digest: str) -> list[str]:
    prefix = "#" if language == "python" else "//"
    return [
        f"{prefix} Generated by Reffin for {domain}. Do not edit by hand.",
        f"{prefix} Input SHA-256: {digest}",
    ]


def material_icon_expression(symbol: str) -> str:
    """Convert a Material Symbols snake_case key to Flutter's Icons member."""
    if not SNAKE_CASE.fullmatch(symbol):
        raise ValueError(f"invalid Material symbol {symbol!r}")
    return f"Icons.{symbol}"
